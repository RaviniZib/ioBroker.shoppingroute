    function resolveLanguage(value) {
        const locale = String(value || '').trim().toLowerCase().replace(/_/g, '-');
        if (Object.prototype.hasOwnProperty.call(translations, locale)) return locale;
        const base = locale.split('-')[0];
        if (base === 'zh') return 'zh-cn';
        return Object.prototype.hasOwnProperty.call(translations, base) ? base : 'en';
    }

    window.ShoppingRouteBackupI18n = { translations, resolveLanguage };
